export function t(lang, key, vars = {}) {
  const s = M[lang]?.[key] ?? M.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** Language for messages: explicit choice, then the account, then what this phone chose on USSD, then English. */
export function langFor(db, { lang, user, phone } = {}) {
  if (lang && LANGS[lang]) return lang;
  if (user?.lang && LANGS[user.lang]) return user.lang;
  if (phone) { const p = db.prepare('SELECT lang FROM phone_prefs WHERE phone = ?').get(phone); if (p && LANGS[p.lang]) return p.lang; }
  return 'en';
}
